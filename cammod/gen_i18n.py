#!/usr/bin/env python3
"""Generates I18n.java from the translation JSON files (run with python3 -I)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
I18N = os.path.join(HERE, 'i18n')
OUT = os.path.join(HERE, 'src', 'org', 'acerhizm', 'cammod', 'I18n.java')


def load(name):
    with open(os.path.join(I18N, name), encoding='utf-8') as f:
        return json.load(f)


def java(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    en = load('en.json')
    en.update(load('en_extra.json'))
    en.update(load('en_lab.json'))
    en.update(load('en_r3.json'))
    en.update(load('en_r4.json'))
    keys = list(en)
    extra = load('extra.json')
    lab = load('lab1.json')
    lab.update(load('lab2.json'))
    for group in ('r3_A.json', 'r3_B.json', 'r3_C.json', 'r4.json'):
        for loc, strings in load(group).items():
            lab.setdefault(loc, {}).update(strings)
    table = {}
    for group in ('A.json', 'B.json', 'C.json'):
        for loc, strings in load(group).items():
            merged = dict(strings)
            merged.update(extra[loc])
            merged.update(lab[loc])
            # Brand line, the same in every language.
            merged['category'] = en['category']
            missing = [k for k in keys if not merged.get(k, '').strip()]
            if missing:
                sys.exit(f'{loc}: missing {missing}')
            table[loc] = merged
    if len(table) != 79:
        sys.exit(f'expected 79 locales, got {len(table)}')
    if table['tr']['live_photo_title'] != 'Canlı anlar':
        sys.exit('tr live_photo_title must be "Canlı anlar"')

    lines = [
        '// Generated by cammod/gen_i18n.py from i18n/*.json; do not edit.',
        'package org.acerhizm.cammod;',
        '',
        'import android.content.Context;',
        'import java.util.HashMap;',
        'import java.util.Locale;',
        '',
        'final class I18n {',
        '    private static final String[] KEYS = {' + ', '.join(java(k) for k in keys) + '};',
        '    private static final HashMap<String, String[]> TABLE = new HashMap<>();',
        '    private static final String[] EN = {' + ', '.join(java(en[k]) for k in keys) + '};',
        '',
        '    static {',
    ]
    for loc in sorted(table):
        vals = ', '.join(java(table[loc][k]) for k in keys)
        lines.append(f'        TABLE.put({java(loc)}, new String[] {{{vals}}});')
    lines += [
        '    }',
        '',
        '    private I18n() {}',
        '',
        '    static String get(Context ctx, String key) {',
        '        int i = java.util.Arrays.asList(KEYS).indexOf(key);',
        '        if (i < 0) return key;',
        '        String[] row = row(ctx.getResources().getConfiguration().getLocales().get(0));',
        '        return row != null ? row[i] : EN[i];',
        '    }',
        '',
        '    /** Same lookup order as Android resources: language-rREGION, then language. */',
        '    static String[] row(Locale l) {',
        '        String lang = l.getLanguage();',
        '        // Android resource qualifiers use the legacy ISO codes.',
        '        if (lang.equals("id")) lang = "in";',
        '        else if (lang.equals("he")) lang = "iw";',
        '        String region = l.getCountry();',
        '        if (lang.equals("zh")) {',
        '            String script = l.getScript();',
        '            if (region.isEmpty()) region = "Hant".equals(script) ? "TW" : "CN";',
        '            if (region.equals("MO")) region = "HK";',
        '            else if (region.equals("SG")) region = "CN";',
        '        }',
        '        String[] r = region.isEmpty() ? null : TABLE.get(lang + "-r" + region);',
        '        if (r == null) r = TABLE.get(lang);',
        '        // English without its own regional table (e.g. en-US) uses the base strings.',
        '        if (r == null && !lang.equals("en")) {',
        '            // e.g. "as" only ships as as-rIN: take the first regional table of the language.',
        '            for (java.util.Map.Entry<String, String[]> e : TABLE.entrySet()) {',
        '                if (e.getKey().startsWith(lang + "-r")) return e.getValue();',
        '            }',
        '        }',
        '        return r;',
        '    }',
        '}',
    ]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{OUT}: {len(table)} locales, {len(keys)} keys')


if __name__ == '__main__':
    main()
